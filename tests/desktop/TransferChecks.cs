using System;
using System.IO;
using System.Linq;
using System.Text;
using AppShield;

internal static class TransferChecks
{
    public static void Run()
    {
        var root = Path.Combine(Path.GetTempPath(), "AppShield.TransferCheck." + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            var broker = new TransferBroker(Path.Combine(root, "profile-data"));
            var id = Guid.NewGuid();
            var other = Guid.NewGuid();
            byte[] bytes = { 1, 2, 3, 4 };
            string source = Path.Combine(root, "sample.bin");
            File.WriteAllBytes(source, bytes);
            string first = broker.Stage(id, source), second = broker.Stage(id, source);
            Assert(first != second && File.ReadAllBytes(first).SequenceEqual(bytes), "independent outgoing copies");
            string stagedText = broker.StageText(id, "测试 👋");
            Assert(new UTF8Encoding(false, true).GetString(File.ReadAllBytes(stagedText)) == "测试 👋", "UTF-8 outgoing");
            Denies(() => broker.StageText(id, "bad\0text"));

            var incoming = Path.Combine(broker.Folder(id, true), "reply.txt");
            File.WriteAllBytes(incoming, new byte[] { 0xEF, 0xBB, 0xBF, 0xEF, 0xBB, 0xBF, 0x41 });
            Assert(broker.ReadIncomingText(id, incoming) == "\uFEFFA", "strip a single UTF-8 byte order mark");
            Denies(() => broker.ReadIncomingText(other, incoming));
            Denies(() => broker.Export(other, incoming, Path.Combine(root, "wrong.txt"), false));
            Denies(() => broker.Export(id, incoming, Path.Combine(broker.Folder(other, true), "bad.txt"), false));
            File.WriteAllBytes(incoming, new byte[] { 0xff, 0xff });
            Denies(() => broker.ReadIncomingText(id, incoming));
            File.WriteAllText(incoming, "ok\u0000binary");
            Denies(() => broker.ReadIncomingText(id, incoming));
            File.WriteAllBytes(incoming, new byte[TransferBroker.MaxTextBytes + 1]);
            Denies(() => broker.ReadIncomingText(id, incoming));
            File.WriteAllBytes(incoming, bytes);

            var dest = Path.Combine(root, "export.bin");
            File.WriteAllText(dest, "keep");
            Denies(() => broker.Export(id, incoming, dest, false));
            Assert(File.ReadAllText(dest) == "keep" && Directory.GetFiles(root, ".appshield-*.tmp").Length == 0,
                "collision preserves destination and cleans unpublished file");
            broker.Export(id, incoming, dest, true);
            Assert(File.ReadAllBytes(dest).SequenceEqual(bytes) && Zone(dest).Contains("ZoneId=3"), "export and mark");
            using (var locked = File.Open(dest, FileMode.Open, FileAccess.Read, FileShare.Read))
                Denies(() => broker.Export(id, incoming, dest, true));

            using (var h = SafeFiles.CreateFile(incoming + ":Zone.Identifier", 0x40000000, 7, IntPtr.Zero, 2, 0, IntPtr.Zero))
            using (var s = new FileStream(h, FileAccess.Write))
            {
                byte[] marker = Encoding.ASCII.GetBytes("[ZoneTransfer]\r\nZoneId=4\r\nHostUrl=https://example.invalid/");
                s.Write(marker, 0, marker.Length);
            }
            broker.Export(id, incoming, dest, true);
            Assert(Zone(dest).Contains("ZoneId=4") && !Zone(dest).Contains("HostUrl"), "restricted zone preserved");
            Assert(Zone(broker.Stage(id, dest)).Contains("ZoneId=4"), "outgoing copy retains zone");
            Denies(() => broker.Export(id, incoming, dest + ":extra", true));
        }
        finally
        {
            // All contents in this newly created fixture are generated by the controls above.
            var parent = Path.GetFullPath(Path.GetTempPath()).TrimEnd('\\');
            if (!string.Equals(Path.GetDirectoryName(Path.GetFullPath(root)), parent, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("Unexpected transfer fixture root.");
            Directory.Delete(root, true);
        }
    }

    private static string Zone(string path)
    {
        using (var h = SafeFiles.CreateFile(path + ":Zone.Identifier", 0x80000000, 7, IntPtr.Zero, 3, 0, IntPtr.Zero))
        using (var stream = new FileStream(h, FileAccess.Read))
        using (var reader = new StreamReader(stream, Encoding.ASCII)) return reader.ReadToEnd();
    }
    private static void Denies(Action action)
    {
        try { action(); }
        catch (IOException) { return; }
        catch (InvalidDataException) { return; }
        catch (DecoderFallbackException) { return; }
        throw new Exception("Transfer operation should have been refused.");
    }
    private static void Assert(bool value, string message)
    {
        if (!value) throw new Exception("Transfer regression: " + message);
    }
}
